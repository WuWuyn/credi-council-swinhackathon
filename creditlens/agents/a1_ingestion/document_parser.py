    def _parse_household(self, text: str) -> dict[str, Any]:
        """Parse Sổ hộ khẩu PDF."""
        kv = self._extract_key_value(text)
        fields = {}
        confidence = {}

        field_map = {
            # Vietnamese diacritics versions
            "Họ và tên chủ hộ": ("head_of_household", 0.95),
            "Tổng số nhân khẩu": ("family_members_count", 0.92),
            "Số con": ("children_count", 0.90),
            "Tình trạng hôn nhân chủ hộ": ("marital_status", 0.92),
            "Tình trạng hôn nhân": ("marital_status", 0.92),
            # ASCII fallbacks
            "Ho va ten chu ho": ("head_of_household", 0.95),
            "Tong so nhan khau": ("family_members_count", 0.92),
            "So con": ("children_count", 0.90),
            "Tinh trang hon nhan chu ho": ("marital_status", 0.92),
            "Tinh trang hon nhan": ("marital_status", 0.92),
        }

        for kv_key, (field_name, conf) in field_map.items():
            if kv_key in kv:
                fields[field_name] = kv[kv_key]
                confidence[field_name] = conf

        # Parse numeric fields
        if "family_members_count" in fields:
            nums = re.findall(r"\d+", str(fields["family_members_count"]))
            if nums:
                fields["family_members_count"] = int(nums[0])

        if "children_count" in fields:
            nums = re.findall(r"\d+", str(fields["children_count"]))
            if nums:
                fields["children_count"] = int(nums[0])

        # Count family members with "Con" relationship
        con_count = len(re.findall(
            r"Quan hệ với chủ hộ:\s*Con|Quan he voi chu ho:\s*Con",
            text, re.IGNORECASE
        ))
        if con_count > 0 and "children_count" not in fields:
            fields["children_count"] = con_count
            confidence["children_count"] = 0.85

        return {"fields": fields, "confidence": confidence}

