class LocalDocumentParser:
    """Local PDF parser using PyMuPDF.

    # LOCAL_SUB: Replace with TextractService for AWS deployment.
    # See LOCAL_SUBSTITUTIONS.md for migration guide.

    Parses Vietnamese PDF documents to extract key-value fields:
    - CCCD → identity, gender, DOB, addresses
    - Hợp đồng lao động → employer, salary, position, start date
    - Sổ hộ khẩu → family members, marital status
    - Thẩm định nhà ở → housing quality, area, construction year
    - Đơn vay → loan amount, term, purpose
    """

    # Field pattern: "Label:  Value" or "Label:Value"
    FIELD_RE = re.compile(r"^(.+?):\s+(.+)$", re.MULTILINE)

    def extract_document(self, pdf_path: str | Path, doc_type: str = "auto") -> dict[str, Any]:
        """Extract fields from a PDF document.

        Args:
            pdf_path: Path to PDF file.
            doc_type: Document type: "cccd", "employment", "household",
                      "housing", "loan_application", "auto".

        Returns:
            Dict with: fields, confidence, doc_type, raw_text
        """
        pdf_path = Path(pdf_path)
        if not pdf_path.exists():
            logger.warning(f"PDF not found: {pdf_path}")
            return {"doc_type": doc_type, "fields": {}, "confidence": {}, "raw_text": ""}

        # Extract text from all pages
        doc = fitz.open(str(pdf_path))
        full_text = "\n".join(page.get_text() for page in doc)
        doc.close()

        logger.info(f"Extracted {len(full_text)} chars from {pdf_path.name}")

        # Auto-detect doc type
        if doc_type == "auto":
            doc_type = self._detect_doc_type(full_text, pdf_path.name)

        # Parse based on doc type
        parsers = {
            "cccd": self._parse_cccd,
            "employment": self._parse_employment,
            "household": self._parse_household,
            "housing": self._parse_housing,
            "loan_application": self._parse_loan_application,
        }

        parser = parsers.get(doc_type, self._parse_generic)
        result = parser(full_text)
        result["doc_type"] = doc_type
        result["raw_text"] = full_text

        return result

    def _detect_doc_type(self, text: str, filename: str) -> str:
        """Auto-detect document type from text content or filename."""
        text_lower = text.lower()
        fname_lower = filename.lower()

        # Support both ASCII and Vietnamese diacritics
        if "cccd" in fname_lower or "căn cước" in text_lower or "can cuoc" in text_lower or "cmnd" in fname_lower:
            return "cccd"
        if "hợp đồng lao động" in text_lower or "hop dong lao dong" in text_lower or "hop_dong" in fname_lower:
            return "employment"
        if "hộ khẩu" in text_lower or "ho khau" in text_lower or "ho_khau" in fname_lower:
            return "household"
        if "thẩm định" in text_lower or "tham dinh" in text_lower or "nhà ở" in text_lower or "nha o" in text_lower or "tham_dinh" in fname_lower:
            return "housing"
        if "đơn vay" in text_lower or "don vay" in text_lower or "đề nghị vay" in text_lower or "de nghi vay" in text_lower or "don_vay" in fname_lower:
            return "loan_application"
        return "unknown"

    def _extract_key_value(self, text: str) -> dict[str, str]:
        """Extract all key:value pairs from text."""
        fields = {}
        for match in self.FIELD_RE.finditer(text):
            key = match.group(1).strip()
            value = match.group(2).strip()
            fields[key] = value
        return fields

